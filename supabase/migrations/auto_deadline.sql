/* =========================================================
   Авто-дедлайны по этапам.
   Запуск: Supabase Studio → SQL Editor → вставить → Run.
   Скрипт идемпотентный: повторный прогон ничего не ломает.

   Что делает:
   1. Разрешаем участникам менять колонку ddl — это нужно, чтобы
      авто-дедлайн, который ставится при переносе карточки,
      сохранялся у всех, а не только у админа.
   2. Бэкфилл: карточкам, у которых дедлайна ещё нет, ставим
      рекомендуемую дату, отсчитанную от сегодняшнего дня.
   ========================================================= */

/* ---------- 1. Права: добавляем ddl в обновляемые колонки ---------- */
revoke update on public.cards from anon, authenticated;
grant update (stage, who, done_at, archived_at, ddl) on public.cards to anon, authenticated;

/* ---------- 2. Бэкфилл дедлайнов для карточек, где их ещё нет ----------
   Сроки по этапам (дни):
   1 · запись вокала     — 10
   2 · отслушка          —  5
   3 · правки            —  7
   4 · сведение/тюн/тайм — 14
   5 · арт               — 14
   6 · видео             — 10                                          */
update public.cards
   set ddl = case stage
       when 1 then current_date + 10
       when 2 then current_date + 5
       when 3 then current_date + 7
       when 4 then current_date + 14
       when 5 then current_date + 14
       when 6 then current_date + 10
       else current_date + 7
   end
 where ddl is null;

/* =========================================================
   Проверка: у всех карточек теперь должен стоять дедлайн.
   select id, title, stage, ddl from public.cards where ddl is null;
   ========================================================= */
